"""
Утилиты для работы с историей диалога: извлечение ранее заданных вопросов
и уже собранных переменных от пользователя.
"""
import re
from schemas import ChatMessage


def _extract_user_provided_facts(chat_history: list[ChatMessage]) -> list[str]:
    """
    Собирает фактические ответы пользователя из истории диалога.

    Логика: первое сообщение пользователя — это начальный запрос (не ответ
    на уточнение). Все последующие сообщения пользователя — это ответы на
    уточняющие вопросы ассистента, т.е. собранные переменные/факты.

    Возвращает список строк — содержимое этих ответных сообщений.
    Используется для явной передачи в check_query_sufficiency, чтобы LLM
    гарантированно не переспрашивал уже предоставленную информацию.
    """
    users_vars = {}
    
    for msg in chat_history:
        users_vars.update(msg.variables)
    print('-'*100)
    print(users_vars)
    print('-'*100)
    # Пропускаем первое сообщение (исходный запрос), берём только ответы на уточнения
    return users_vars


